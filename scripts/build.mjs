// Builds the interactive directory's data from README.md (source of truth):
//   docs/data/catalog.json  - categories, tools, labels, stats
//   docs/js/icons.js        - generated SVG symbol sprite (only used icons)
// Usage:
//   node scripts/build.mjs           generate
//   node scripts/build.mjs --check   verify committed output matches README (CI)
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { parseReadme, ACCESS_LABELS } from "./parse-readme.mjs";
import { BRAND_TOOLS, KEYWORD_RULES, CATEGORY_ICONS, LABEL_ICONS } from "./icon-map.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const DOCS = join(ROOT, "docs");
const LUCIDE_DIR = join(HERE, "icon-sources", "lucide");
const BRAND_DIR = join(HERE, "icon-sources", "brands");

// Extra icons the hand-written UI references (search box, chips, buttons...).
const UI_ICONS = [
  "search", "x", "moon", "sun", "star", "shuffle", "history", "copy", "share-2",
  "external-link", "filter", "rotate-ccw", "menu", "chevron-down", "chevron-right",
  "chevron-up", "home", "info", "circle-check", "circle-x", "arrow-up-down",
  "layout-grid", "list", "wrench", "sparkles", "tag", "folder", "check", "link",
  "book-open", "heart-handshake", "lightbulb", "globe", "eye", "git-fork",
  "circle-help", "bookmark",
];

function innerSvg(file) {
  const svg = readFileSync(file, "utf8");
  const m = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>\s*$/);
  if (!m) throw new Error(`Cannot parse svg: ${file}`);
  return m[1].replace(/<title>[\s\S]*?<\/title>/g, "").replace(/<!--[\s\S]*?-->/g, "").trim();
}

function loadIconSet(dir) {
  const map = new Map();
  for (const f of readdirSync(dir)) {
    if (f.endsWith(".svg")) map.set(f.replace(/\.svg$/, ""), innerSvg(join(dir, f)));
  }
  return map;
}

const pick = (rules, text) => {
  const lower = text.toLowerCase();
  for (const [re, icon] of rules) if (re.test(lower)) return icon;
  return null;
};

function build() {
  const { categories, tools, stats, warnings } = parseReadme();
  const lucide = loadIconSet(LUCIDE_DIR);
  const brands = loadIconSet(BRAND_DIR);

  const used = new Set(UI_ICONS);
  const usedBrands = new Set();
  const fallbacks = new Map();

  for (const tool of tools) {
    // 1. official brand mark (only when the SVG was actually bundled)
    const slug = BRAND_TOOLS[tool.name];
    if (slug && brands.has(slug)) {
      tool.icon = `b-${slug}`;
      usedBrands.add(slug);
      continue;
    }
    // 2-4. keyword rules: name, then subcategory, then description
    const icon =
      pick(KEYWORD_RULES, tool.name) ||
      (tool.subcategory ? pick(KEYWORD_RULES, tool.subcategory) : null) ||
      pick(KEYWORD_RULES, tool.description) ||
      // 5. category icon
      CATEGORY_ICONS[tool.categoryId] ||
      // 6. project wrench
      "wrench";
    const resolved = lucide.has(icon) ? icon : "wrench";
    if (icon !== resolved) fallbacks.set(tool.name, `${icon} -> ${resolved}`);
    tool.icon = resolved;
    used.add(resolved);
  }

  for (const cat of categories) {
    const ci = CATEGORY_ICONS[cat.id];
    cat.icon = lucide.has(ci) ? ci : "wrench";
    used.add(cat.icon);
    for (const sub of cat.subcategories) {
      const si = pick(KEYWORD_RULES, sub.name) || cat.icon;
      sub.icon = lucide.has(si) ? si : cat.icon;
      used.add(sub.icon);
    }
  }

  const labelOut = ACCESS_LABELS.map((l) => ({
    ...l,
    icon: lucide.has(LABEL_ICONS[l.id]) ? LABEL_ICONS[l.id] : "circle-check",
    count: stats.labels[l.id],
  }));
  for (const l of labelOut) used.add(l.icon);

  // ---- sprite ------------------------------------------------------------
  const symbols = [];
  for (const id of [...used].sort()) {
    const body = lucide.get(id);
    if (body == null) continue;
    symbols.push(
      `<symbol id="i-${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${body}</symbol>`,
    );
  }
  for (const slug of [...usedBrands].sort()) {
    symbols.push(`<symbol id="i-b-${slug}" viewBox="0 0 24 24" fill="currentColor">${brands.get(slug)}</symbol>`);
  }
  const sprite =
    `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" ` +
    `style="position:absolute;width:0;height:0;overflow:hidden">${symbols.join("")}</svg>\n`;
  const iconsJs = `/* Generated by scripts/build.mjs - do not edit by hand. */\n` +
    `window.AT_ICON_SPRITE = ${JSON.stringify(sprite)};\n`;

  // ---- catalog -----------------------------------------------------------
  const catalog = {
    generatedFrom: "README.md",
    generatedAt: null, // filled by caller only for human-readable debug, kept stable for --check
    entryCount: stats.tools,
    labels: labelOut,
    categories: categories.map((c) => ({
      id: c.id,
      name: c.name,
      icon: c.icon,
      count: c.toolCount,
      subcategories: c.subcategories.map((s) => ({ id: s.id, name: s.name, icon: s.icon, count: s.toolCount })),
    })),
    tools: tools.map((t) => ({
      id: t.id,
      name: t.name,
      url: t.url,
      description: t.description,
      catId: t.categoryId,
      subId: t.subcategoryId,
      tags: t.tags,
      notes: t.notes,
      icon: t.icon,
      iconType: t.icon.startsWith("b-") ? "brand" : "line",
    })),
    stats: {
      tools: stats.tools,
      categories: stats.categories,
      subcategories: stats.subcategories,
      openSource: stats.openSource,
      freeTier: stats.freeTier,
      localOffline: stats.localOffline,
    },
  };
  const catalogJson = JSON.stringify(catalog) + "\n";
  return { catalogJson, iconsJs, warnings, tools, categories, fallbacks, used, lucide, brands };
}

const checkMode = process.argv.includes("--check");
const result = build();

for (const w of result.warnings) console.warn("  ! " + w);

if (checkMode) {
  const expected = [
    [join(DOCS, "data", "catalog.json"), result.catalogJson],
    [join(DOCS, "js", "icons.js"), result.iconsJs],
  ];
  let ok = true;
  for (const [file, content] of expected) {
    if (!existsSync(file)) {
      console.error(`CHECK FAILED: missing ${file}`);
      ok = false;
      continue;
    }
    const onDisk = readFileSync(file, "utf8");
    if (onDisk !== content) {
      console.error(`CHECK FAILED: ${file} is out of sync with README.md`);
      ok = false;
    }
  }
  console.log(ok ? "CHECK OK: docs data is in sync with README.md" : "");
  process.exit(ok ? 0 : 1);
}

mkdirSync(join(DOCS, "data"), { recursive: true });
mkdirSync(join(DOCS, "js"), { recursive: true });
writeFileSync(join(DOCS, "data", "catalog.json"), result.catalogJson);
writeFileSync(join(DOCS, "js", "icons.js"), result.iconsJs);

const brandCount = result.tools.filter((t) => t.icon.startsWith("b-")).length;
console.log(
  `built: ${result.tools.length} tools, ${result.categories.length} categories, ` +
    `${result.used.size} line icons + ${brandCount} brand-icon tools in use`,
);
console.log(`catalog.json: ${Math.round(result.catalogJson.length / 1024)} KB, icons.js: ${Math.round(result.iconsJs.length / 1024)} KB`);
if (result.fallbacks.size) console.log(`icon fallbacks (requested icon missing): ${result.fallbacks.size}`);
